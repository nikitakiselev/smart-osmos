#define TDS_CALIBRATION_OFFSET 0.0f

/** Температурная компенсация (коэффициент на градус, опционально) */
#define TDS_TEMP_COEFF      0.02f

// =============================================================================
// РАСХОДОМЕРЫ
// =============================================================================

/**
 * Количество импульсов на литр (зависит от модели расходомера).
 * Типичные значения: 450, 550, 750 импульсов/литр.
 */
#define FLOW_PULSES_PER_LITER  450

/** Минимальный интервал между импульсами, мкс (защита от дребезга) */
